import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

import { format, resolveConfig } from "prettier";
import ts from "typescript";
import { z } from "zod";

const layersSchema = z.object({
  layers: z.array(z.array(z.string()).min(1)).min(1),
  sameLayerEdges: z.array(z.object({ from: z.string(), to: z.string(), why: z.string().min(1) })),
  rootDeepImportExceptions: z.array(z.object({ file: z.string(), why: z.string().min(1) })),
});
export type Layers = z.infer<typeof layersSchema>;
export type Edge = readonly [from: string, to: string];
export interface ModuleGraph {
  modules: string[];
  edges: Edge[];
}

export function graphPaths(repoRoot: string) {
  return {
    modulesDir: path.join(repoRoot, "apps/server/src/modules"),
    layersFile: path.join(repoRoot, "apps/server/src/modules/layers.json"),
    json: path.join(repoRoot, "docs/diagrams/module-graph.json"),
    markdown: path.join(repoRoot, "docs/diagrams/module-graph.md"),
  };
}

export function loadLayers(file: string): Layers {
  return layersSchema.parse(JSON.parse(readFileSync(file, "utf8")));
}

function sourceFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(full);
    return entry.name.endsWith(".ts") && !entry.name.endsWith(".test.ts") ? [full] : [];
  });
}

const byEdge = (a: Edge, b: Edge): number => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]);

export function readModuleGraph(modulesDir: string): ModuleGraph {
  const modules = readdirSync(modulesDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const seen = new Set<string>();
  const edges: Edge[] = [];
  for (const name of modules) {
    for (const file of sourceFiles(path.join(modulesDir, name))) {
      for (const { fileName } of ts.preProcessFile(readFileSync(file, "utf8"), true, true).importedFiles) {
        if (!fileName.startsWith(".")) continue;
        const [target] = path.relative(modulesDir, path.resolve(path.dirname(file), fileName)).split(path.sep);
        if (target === undefined || target === name || !modules.includes(target)) continue;
        const key = `${name} ${target}`;
        if (seen.has(key)) continue;
        seen.add(key);
        edges.push([name, target]);
      }
    }
  }
  return { modules, edges: edges.sort(byEdge) };
}

export function forbiddenEdges(edges: readonly Edge[], layers: Layers): Edge[] {
  const layerOf = new Map(layers.layers.flatMap((names, index) => names.map((name) => [name, index] as const)));
  const sameLayer = new Set(layers.sameLayerEdges.map(({ from, to }) => `${from} ${to}`));
  return edges.filter(([from, to]) => {
    const fromLayer = layerOf.get(from);
    const toLayer = layerOf.get(to);
    if (fromLayer === undefined || toLayer === undefined) return true;
    return !(toLayer < fromLayer || (toLayer === fromLayer && sameLayer.has(`${from} ${to}`)));
  });
}

export function findCycle(edges: readonly Edge[]): string[] | null {
  const next = new Map<string, string[]>();
  for (const [from, to] of edges) next.set(from, [...(next.get(from) ?? []), to]);
  const done = new Set<string>();
  const stack: string[] = [];
  function visit(node: string): string[] | null {
    const at = stack.indexOf(node);
    if (at >= 0) return [...stack.slice(at), node];
    if (done.has(node)) return null;
    stack.push(node);
    for (const to of next.get(node) ?? []) {
      const cycle = visit(to);
      if (cycle) return cycle;
    }
    stack.pop();
    done.add(node);
    return null;
  }
  for (const node of next.keys()) {
    const cycle = visit(node);
    if (cycle) return cycle;
  }
  return null;
}

export function renderGraphJson(graph: ModuleGraph): string {
  return JSON.stringify(
    {
      $comment:
        "Generated by bun run graph:modules from the imports in apps/server/src/modules (test files not counted). Do not edit.",
      modules: graph.modules,
      edges: graph.edges,
    },
    null,
    2
  );
}

export function renderGraphMarkdown(graph: ModuleGraph, layers: Layers): string {
  const placed = new Set(layers.layers.flat());
  const groups = layers.layers.map((names, index) => ({ title: `Layer ${index + 1}`, names }));
  const unplaced = graph.modules.filter((name) => !placed.has(name));
  if (unplaced.length > 0) groups.push({ title: "No layer", names: unplaced });
  const lines = [
    "# Server module graph",
    "",
    "> Generated by `bun run graph:modules` from the imports in `apps/server/src/modules/` (test files not counted). Do not edit: change the code, then run the command. `apps/server/src/modules/layers.test.ts` fails when this file is stale.",
    "",
    `Arrow = "imports". Layer 1 is the lowest. \`platform\` sits below layer 1; the composition roots (\`apps/server/src/*.ts\`, \`apps/server/src/scripts/\`) sit above layer ${layers.layers.length}. Layers and the allowed same-layer edges: \`apps/server/src/modules/layers.json\`. Rules: \`docs/code-patterns.md\` § Layers and borders.`,
    "",
    "```mermaid",
    "flowchart BT",
    ...groups.flatMap(({ title, names }, index) => [
      `  subgraph group${index + 1}["${title}"]`,
      ...names.map((name) => `    ${name}`),
      "  end",
    ]),
    ...graph.edges.map(([from, to]) => `  ${from} --> ${to}`),
    "```",
    "",
  ];
  return lines.join("\n");
}

// lint-staged runs Prettier on staged .md and .json files, so the generator writes Prettier's output.
export async function formatFor(filePath: string, text: string): Promise<string> {
  const config = await resolveConfig(filePath);
  return format(text, { ...config, filepath: filePath });
}
