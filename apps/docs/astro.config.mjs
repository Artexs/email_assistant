// @ts-check
import starlight from "@astrojs/starlight";
import { DOCS_BASE, DOCS_ORIGIN, PRODUCT_NAME } from "@ea/core";
import { defineConfig } from "astro/config";
import cspFinalize from "./integrations/csp-finalize";
import inPlaceCheck from "./integrations/in-place-check";
import linkCheck from "./integrations/link-check";
import publicContent from "./integrations/public-content";
import { IN_PLACE_PAGES, IN_PLACE_SECTION, inPlaceSourcePaths } from "./src/in-place";

// The public docs site (ADR 0030). Starlight's own Expressive Code highlights code, so `markdown.syntaxHighlight` stays on.
export default defineConfig({
  output: "static",
  site: DOCS_ORIGIN,
  base: DOCS_BASE,
  integrations: [
    starlight({
      title: PRODUCT_NAME,
      defaultLocale: "root",
      locales: {
        root: { label: "English", lang: "en" },
        pl: { label: "Polski", lang: "pl" },
      },
      // The one rule of our own: the search button keeps no keyboard hint (a11y, stage 06).
      customCss: ["./src/styles/custom.css"],
      social: [{ icon: "github", label: "GitHub", href: "https://github.com/Artexs/email_assistant" }],
      // The in-place pages sit outside src/content/docs: an autogenerated sidebar would group them by their repository folders.
      // Each content stage adds its section here, before "Operate".
      sidebar: [
        { label: "Start", items: [{ slug: "start" }] },
        { label: "FAQ", items: [{ slug: "faq" }] },
        { label: IN_PLACE_SECTION, items: IN_PLACE_PAGES.map((page) => ({ slug: page.id })) },
      ],
    }),
    // After Starlight: it hashes Starlight's inline scripts and checks every page's CSP (plan D3).
    // The in-place sources are content too: none may hold a script (stage 03).
    cspFinalize({ extraContentFiles: inPlaceSourcePaths() }),
    // It reads the finished files (plan D4).
    publicContent(),
    // After the CSP and public checks: the in-place pages are built and listed, then every same-site link resolves (plan D5, D6).
    inPlaceCheck(),
    linkCheck(),
  ],
  // Astro hashes its own scripts and styles. `cspFinalize` hashes the rest and relaxes `style-src`.
  // No `frame-ancestors`: a meta CSP ignores it (plan Q6). No `'unsafe-eval'` or `'wasm-unsafe-eval'`: Pagefind needs neither.
  security: {
    csp: {
      directives: [
        "default-src 'self'",
        "img-src 'self' data:",
        "font-src 'self'",
        "connect-src 'self'",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'none'",
      ],
    },
  },
});
